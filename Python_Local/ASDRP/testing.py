class AutoencoderClass(torch.nn.Module):
  """
  Deep autoencoder network object (nn.Module) with optional L2 normalization
  of activations in bottleneck layer.

  Args:
    input_size (integer)
        size of input samples

    s2 (boolean)
        whether to L2 normalize activatinos in bottleneck layer

  Returns:
    Autoencoder object inherited from nn.Module class.
  """

  def __init__(self, input_size=784, s2=False): #initializes the autoencoder class, which is a subclass of nn.Module

    super().__init__()

    self.input_size = input_size
    self.s2 = s2

    if s2:#if s2 is true latent space is 3 dim, if not its 2 dim
      self.encoding_size = 3

    else:
      self.encoding_size = 2

    self.enc1 = nn.Linear(self.input_size, int(self.input_size / 2)) #first encoder layer, connected layer that takes the input and reduces its dimensionality by half 
    self.enc1_f = nn.PReLU()
    
    self.enc2 = nn.Linear(int(self.input_size / 2), self.encoding_size * 32) #second encoder layer, changes latent dim to encodinf size tiems 32
    self.enc2_f = nn.PReLU()
    self.enc3 = nn.Linear(self.encoding_size * 32, self.encoding_size)
    self.enc3_f = nn.PReLU()
    
    self.dec1 = nn.Linear(self.encoding_size, self.encoding_size * 32) #first decoding layer, expands the latent vector
    self.dec1_f = nn.PReLU()
    self.dec2 = nn.Linear(self.encoding_size * 32, int(self.input_size / 2)) #second decoding layer, reduces the dim back to half
    self.dec2_f = nn.PReLU()
    self.dec3 = nn.Linear(int(self.input_size / 2), self.input_size) #final decoding layer, reconstructs to orginal input size
    self.dec3_f = nn.Sigmoid()

  def encoder(self, x): 
    """
    Encoder component.
    """
    x = self.enc1_f(self.enc1(x)) #passes the input through first layer of encoder and applies PReLU activation function (3x)
    x = self.enc2_f(self.enc2(x))
    x = self.enc3_f(self.enc3(x))

    if self.s2:
        x = nn.functional.normalize(x, p=2, dim=1) # if s2 is true, applies L2 normalization to the activations in the bottleneck layer

    return x

  def decoder(self, x): 
    """
    Decoder component.
    """
    x = self.dec1_f(self.dec1(x)) #passes the input through decoding layers (3x)
    x = self.dec2_f(self.dec2(x))
    x = self.dec3_f(self.dec3(x))

    return x

  def forward(self, x): #defines the forward pass of the autoencoder, which takes an input x, passes it through the encoder to obtain the latent representation, and then passes that representation through the decoder to reconstruct the original input. 
    """
    Forward pass.
    """
    x = self.encoder(x)
    x = self.decoder(x)

    return x

