def plot_row(images, image_shape, **kwargs): #plots a row of images each image reshpaed
    n = len(images[0])
    fig, axes = plt.subplots(len(images), n, figsize=(n * 2, len(images) * 2))
    for i, row in enumerate(images):
        for j, img in enumerate(row):
            axes[i, j].imshow(img.reshape(image_shape), cmap='gray')
            axes[i, j].axis('off')
    plt.show()


def plot_latent_generative(latent, labels, decoder, image_shape, s2=False): #plots the reconstructions of the first 10 test images, which are generated by passing the latent representations through the decoder. 
    with torch.no_grad():
        recon = decoder(latent[:10])
    plot_row([recon], image_shape=image_shape)


def plot_latent_ab(latent_a, latent_b, labels, idx, decoder, image_shape, title_a='', title_b='', s2=False): 
    with torch.no_grad():
        recon_a = decoder(latent_a[idx])
        recon_b = decoder(latent_b[idx])
    plot_row([[recon_a], [recon_b]], image_shape=image_shape)


def downloadMNIST():
 
  X, y = fetch_openml('mnist_784', version=1, return_X_y=True, as_frame=False) #fetches the MNIST dataset, which consists of 70,000 grayscale images of handwritten digits (0-9) along with their corresponding labels. The function returns the data as two separate arrays: X contains the pixel values of the images, and y contains the labels for each image. 
  n_train = 60000 #specifies the number of training samples from the MNIST dataset
  n_test = 10000 #specifies the number of test samples from the MNIST dataset. 
  train_idx = np.arange(0, n_train) #creates an array of indices for the training samples,used to select the training samples from the dataset.
  test_idx = np.arange(n_train, n_train + n_test) #creates an array of indices for the test samples, used to select the test samples from the dataset.
  x_train, y_train = X[train_idx], y[train_idx] #selects the training samples and their corresponding labels from the dataset, x_train containing the pixel values of the training and y_train containing the labels for those images.
  x_test, y_test = X[test_idx], y[test_idx] #selects the test samples and their corresponding labels from the dataset, same as training but for test data
  # Transform np.ndarrays to torch.Tensor
  x_train = torch.from_numpy(np.reshape(x_train,
                                        (len(x_train),
                                         28, 28)).astype(np.float32)) #reshapes the training data from a 2D array of shape (60000, 784) to a 3D array of shape (60000, 28, 28), where each image is represented as a 28x28 pixel grid. The pixel values are also converted to float32 data type for compatibility with PyTorch tensors.
  x_test = torch.from_numpy(np.reshape(x_test, #same thing but for test data
                                       (len(x_test),
                                        28, 28)).astype(np.float32))

  y_train = torch.from_numpy(y_train.astype(int)) #converts the training labels from a numpy array to a PyTorch tensor
  y_test = torch.from_numpy(y_test.astype(int)) #same thing but for test

  return (x_train, y_train, x_test, y_test)



